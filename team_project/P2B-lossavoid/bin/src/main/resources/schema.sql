CREATE TABLE MENU_MASTER (
    MENU_CODE VARCHAR2(20) PRIMARY KEY,
    MENU_NAME VARCHAR2(100) NOT NULL,
    PRICE NUMBER(10) NOT NULL,
    CATEGORY VARCHAR2(40),
    PREP_STATION VARCHAR2(20),
    COOK_TIME_MIN NUMBER(5),
    STOCK_QTY NUMBER(8),
    SOLD_OUT NUMBER(1) DEFAULT 0 NOT NULL,
    ALLERGENS VARCHAR2(400)
);

CREATE TABLE ORDERS (
    ORDER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TABLE_NO VARCHAR2(10) NOT NULL,
    GUEST_COUNT NUMBER(3),
    STATUS VARCHAR2(20) DEFAULT 'WAITING' NOT NULL,
    ORDER_METHOD VARCHAR2(40),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE ORDER_ITEMS (
    ORDER_ITEM_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ORDER_ID NUMBER NOT NULL,
    MENU_CODE VARCHAR2(20) NOT NULL,
    MENU_NAME VARCHAR2(100) NOT NULL,
    PRICE NUMBER(10) NOT NULL,
    QTY NUMBER(5) NOT NULL,
    COOK_STATUS VARCHAR2(20) DEFAULT 'WAITING' NOT NULL,
    SERVED NUMBER(1) DEFAULT 0 NOT NULL,
    SERVED_AT TIMESTAMP,
    NOTE VARCHAR2(400),
    CONSTRAINT FK_ORDER_ITEMS_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS (ORDER_ID),
    CONSTRAINT FK_ORDER_ITEMS_MENU FOREIGN KEY (MENU_CODE) REFERENCES MENU_MASTER (MENU_CODE)
);

CREATE TABLE STAFF_MASTER (
    STAFF_CODE VARCHAR2(20) PRIMARY KEY,
    STAFF_NAME VARCHAR2(80) NOT NULL,
    PASSWORD_HASH VARCHAR2(100),
    ROLE VARCHAR2(20) DEFAULT 'EMPLOYEE' NOT NULL,
    ENABLED NUMBER(1) DEFAULT 1 NOT NULL
);

CREATE TABLE TABLE_STATUS (
    TABLE_NO VARCHAR2(10) PRIMARY KEY,
    GUEST_COUNT NUMBER(3),
    TABLE_STATE VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
