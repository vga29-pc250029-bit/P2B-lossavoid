-- 基本6表がある既存環境へ必要な列・注文詳細表・外部キー・採番を追加する。すべての旧定義や参照切れデータを修復する処理ではない。
-- Add only the fields required by the existing web screens. No business data is imported.
DECLARE
    object_count NUMBER;
    -- 追加は列がない場合だけ行う。既存列の型変更や、すべての列の不足を網羅した修復ではない。
    PROCEDURE add_column_if_missing(table_name_in VARCHAR2, column_name_in VARCHAR2, definition_in VARCHAR2) IS
        column_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO column_count FROM USER_TAB_COLUMNS
        WHERE TABLE_NAME = table_name_in AND COLUMN_NAME = column_name_in;
        IF column_count = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || table_name_in || ' ADD (' || column_name_in || ' ' || definition_in || ')';
        END IF;
    END;
    PROCEDURE add_sequence_if_missing(sequence_name_in VARCHAR2, table_name_in VARCHAR2, id_column_in VARCHAR2) IS
        sequence_count NUMBER;
        next_id NUMBER;
    BEGIN
        SELECT COUNT(*) INTO sequence_count FROM USER_SEQUENCES WHERE SEQUENCE_NAME = sequence_name_in;
        IF sequence_count = 0 THEN
            EXECUTE IMMEDIATE 'SELECT NVL(MAX(' || id_column_in || '), 0) + 1 FROM ' || table_name_in INTO next_id;
            EXECUTE IMMEDIATE 'CREATE SEQUENCE ' || sequence_name_in || ' START WITH ' || next_id || ' INCREMENT BY 1 NOCACHE';
        END IF;
    END;
BEGIN
    add_column_if_missing('MENUS', 'PREP_STATION', 'VARCHAR2(20) DEFAULT ''kitchen'' NOT NULL');
    add_column_if_missing('MENUS', 'STOCK_QTY', 'NUMBER(8)');
    add_column_if_missing('MENUS', 'SOLD_OUT', 'NUMBER(1) DEFAULT 0 NOT NULL');
    add_column_if_missing('ORDERS', 'ORDER_METHOD', 'VARCHAR2(40)');
    add_column_if_missing('ORDERS', 'UPDATED_AT', 'TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL');
    add_column_if_missing('STAFFS', 'STAFF_CODE', 'VARCHAR2(20)');

    EXECUTE IMMEDIATE 'UPDATE STAFFS SET STAFF_CODE = TO_CHAR(STAFF_ID) WHERE STAFF_CODE IS NULL';
    SELECT COUNT(*) INTO object_count FROM USER_INDEXES WHERE INDEX_NAME = 'UX_STAFFS_CODE';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UX_STAFFS_CODE ON STAFFS (UPPER(STAFF_CODE))';
    END IF;

    SELECT COUNT(*) INTO object_count FROM USER_TABLES WHERE TABLE_NAME = 'ORDER_DETAILS';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE ORDER_DETAILS (
            ORDER_DETAIL_ID NUMBER(10) PRIMARY KEY,
            ORDER_ID NUMBER(10) NOT NULL,
            MENU_ID NUMBER(10) NOT NULL,
            MENU_NAME VARCHAR2(100) NOT NULL,
            PRICE NUMBER(8) NOT NULL,
            QUANTITY NUMBER(5) NOT NULL,
            SERVED NUMBER(1) DEFAULT 0 NOT NULL,
            SERVED_AT TIMESTAMP,
            NOTE VARCHAR2(400),
            CONSTRAINT FK_DETAILS_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS (ORDER_ID),
            CONSTRAINT FK_DETAILS_MENU FOREIGN KEY (MENU_ID) REFERENCES MENUS (MENU_ID))';
    END IF;

    -- 外部キー追加は既存データも検証する。参照先の注文詳細がない調理タスクが残ると起動時に失敗する。
    SELECT COUNT(*) INTO object_count FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME = 'FK_TASK_ORDER_DETAIL';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE COOKING_TASKS ADD CONSTRAINT FK_TASK_ORDER_DETAIL
            FOREIGN KEY (ORDER_DETAIL_ID) REFERENCES ORDER_DETAILS (ORDER_DETAIL_ID)';
    END IF;

    add_sequence_if_missing('SEQ_CUSTOMERS', 'CUSTOMERS', 'CUSTOMER_ID');
    add_sequence_if_missing('SEQ_ORDERS', 'ORDERS', 'ORDER_ID');
    add_sequence_if_missing('SEQ_ORDER_DETAILS', 'ORDER_DETAILS', 'ORDER_DETAIL_ID');
    add_sequence_if_missing('SEQ_COOKING_TASKS', 'COOKING_TASKS', 'TASK_ID');
    add_sequence_if_missing('SEQ_STAFFS', 'STAFFS', 'STAFF_ID');

    SELECT COUNT(*) INTO object_count FROM USER_TABLES WHERE TABLE_NAME = 'CHICKEN_PREP_CONTROL';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE q'[CREATE TABLE CHICKEN_PREP_CONTROL (
            CONTROL_ID NUMBER(1) PRIMARY KEY,
            CONSTRAINT CK_CHICKEN_CONTROL_ID CHECK (CONTROL_ID = 1))]';
    END IF;
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM CHICKEN_PREP_CONTROL WHERE CONTROL_ID = 1' INTO object_count;
    IF object_count = 0 THEN
        BEGIN
            EXECUTE IMMEDIATE 'INSERT INTO CHICKEN_PREP_CONTROL (CONTROL_ID) VALUES (1)';
        EXCEPTION WHEN DUP_VAL_ON_INDEX THEN NULL;
        END;
    END IF;

    SELECT COUNT(*) INTO object_count FROM USER_TABLES WHERE TABLE_NAME = 'CHICKEN_PREP_BATCHES';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE q'[CREATE TABLE CHICKEN_PREP_BATCHES (
            BATCH_ID NUMBER(10) PRIMARY KEY,
            REQUESTED_QTY NUMBER(4) NOT NULL,
            REMAINING_QTY NUMBER(4) DEFAULT 0 NOT NULL,
            WASTED_QTY NUMBER(4) DEFAULT 0 NOT NULL,
            STATUS VARCHAR2(20) NOT NULL,
            SOURCE VARCHAR2(20) DEFAULT 'SYSTEM' NOT NULL,
            REQUESTED_AT TIMESTAMP NOT NULL,
            STARTED_AT TIMESTAMP,
            READY_AT TIMESTAMP,
            EXPIRES_AT TIMESTAMP,
            CONSTRAINT CK_CHICKEN_PREP_QTY CHECK (REQUESTED_QTY >= 2 AND MOD(REQUESTED_QTY, 2) = 0),
            CONSTRAINT CK_CHICKEN_PREP_REMAINING CHECK (REMAINING_QTY >= 0 AND REMAINING_QTY <= REQUESTED_QTY),
            CONSTRAINT CK_CHICKEN_PREP_WASTE CHECK (WASTED_QTY >= 0 AND WASTED_QTY <= REQUESTED_QTY),
            CONSTRAINT CK_CHICKEN_PREP_STATUS CHECK (STATUS IN ('REQUESTED', 'COOKING', 'READY', 'EXPIRED', 'DISCARDED', 'LAPSED')))]';
    END IF;
    SELECT COUNT(*) INTO object_count FROM USER_CONSTRAINTS
    WHERE TABLE_NAME = 'CHICKEN_PREP_BATCHES' AND CONSTRAINT_NAME = 'CK_CHICKEN_PREP_STATUS'
      AND SEARCH_CONDITION_VC LIKE '%LAPSED%';
    IF object_count = 0 THEN
        SELECT COUNT(*) INTO object_count FROM USER_CONSTRAINTS
        WHERE TABLE_NAME = 'CHICKEN_PREP_BATCHES' AND CONSTRAINT_NAME = 'CK_CHICKEN_PREP_STATUS';
        IF object_count > 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE CHICKEN_PREP_BATCHES DROP CONSTRAINT CK_CHICKEN_PREP_STATUS';
        END IF;
        EXECUTE IMMEDIATE q'[ALTER TABLE CHICKEN_PREP_BATCHES ADD CONSTRAINT CK_CHICKEN_PREP_STATUS
            CHECK (STATUS IN ('REQUESTED', 'COOKING', 'READY', 'EXPIRED', 'DISCARDED', 'LAPSED'))]';
    END IF;
    SELECT COUNT(*) INTO object_count FROM USER_INDEXES WHERE INDEX_NAME = 'IX_CHICKEN_PREP_STATUS';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_CHICKEN_PREP_STATUS ON CHICKEN_PREP_BATCHES (STATUS, EXPIRES_AT)';
    END IF;

    SELECT COUNT(*) INTO object_count FROM USER_TABLES WHERE TABLE_NAME = 'CHICKEN_STOCK_USAGE';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE q'[CREATE TABLE CHICKEN_STOCK_USAGE (
            ORDER_DETAIL_ID NUMBER(10) PRIMARY KEY,
            BATCH_ID NUMBER(10),
            USED_AT TIMESTAMP NOT NULL,
            CONSTRAINT FK_CHICKEN_USAGE_DETAIL FOREIGN KEY (ORDER_DETAIL_ID) REFERENCES ORDER_DETAILS (ORDER_DETAIL_ID),
            CONSTRAINT FK_CHICKEN_USAGE_BATCH FOREIGN KEY (BATCH_ID) REFERENCES CHICKEN_PREP_BATCHES (BATCH_ID))]';
    END IF;
    add_sequence_if_missing('SEQ_CHICKEN_PREP_BATCHES', 'CHICKEN_PREP_BATCHES', 'BATCH_ID');

    -- ライス3種はキッチン調理を行わず、注文直後からフロア持出し待ちとして扱う。
    UPDATE COOKING_TASKS
    SET STATUS = 'KITCHEN_READY',
        END_TIME = COALESCE(END_TIME, CURRENT_TIMESTAMP)
    WHERE STATUS IN ('WAITING', 'COOKING')
      AND EXISTS (
          SELECT 1
          FROM ORDER_DETAILS d
          WHERE d.ORDER_DETAIL_ID = COOKING_TASKS.ORDER_DETAIL_ID
            AND d.MENU_ID IN (3101, 3102, 3103)
            AND d.QUANTITY > 0
      );
END;
