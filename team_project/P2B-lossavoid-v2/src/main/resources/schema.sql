-- Fresh lossavoid schema only. Existing installations use db/lossavoid-upgrade.sql.
-- No menu, staff, store, or order data is seeded.
CREATE TABLE CUSTOMERS (
    CUSTOMER_ID NUMBER(10) PRIMARY KEY,
    TABLE_NO VARCHAR2(10) NOT NULL,
    NUMBER_OF_PEOPLE NUMBER(3) NOT NULL,
    VISIT_TIME TIMESTAMP NOT NULL,
    STATUS VARCHAR2(20) NOT NULL
);

CREATE TABLE MENUS (
    MENU_ID NUMBER(10) PRIMARY KEY,
    MENU_NAME VARCHAR2(100) NOT NULL,
    PRICE NUMBER(8) NOT NULL,
    CATEGORY VARCHAR2(30) NOT NULL,
    STANDARD_COOK_TIME NUMBER(5) NOT NULL,
    LEAD_TIME NUMBER(5),
    ALLERGY_INFO VARCHAR2(255),
    PREP_STATION VARCHAR2(20) DEFAULT 'kitchen' NOT NULL,
    STOCK_QTY NUMBER(8),
    SOLD_OUT NUMBER(1) DEFAULT 0 NOT NULL
);

CREATE TABLE ORDERS (
    ORDER_ID NUMBER(10) PRIMARY KEY,
    CUSTOMER_ID NUMBER(10) NOT NULL,
    ORDER_STATUS VARCHAR2(20) NOT NULL,
    ORDER_TIME TIMESTAMP NOT NULL,
    EXPECTED_WAIT_TIME NUMBER(5),
    ORDER_METHOD VARCHAR2(40),
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_ORDERS_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS (CUSTOMER_ID)
);

CREATE TABLE ORDER_DETAILS (
    ORDER_DETAIL_ID NUMBER(10) PRIMARY KEY,
    ORDER_ID NUMBER(10) NOT NULL,
    MENU_ID NUMBER(10) NOT NULL,
    MENU_NAME VARCHAR2(100) NOT NULL,
    PRICE NUMBER(8) NOT NULL,
    QUANTITY NUMBER(5) NOT NULL,
    SERVED NUMBER(1) DEFAULT 0 NOT NULL,
    SERVED_AT TIMESTAMP,
    NOTE VARCHAR2(400),
    CONSTRAINT FK_DETAILS_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS (ORDER_ID),
    CONSTRAINT FK_DETAILS_MENU FOREIGN KEY (MENU_ID) REFERENCES MENUS (MENU_ID)
);

CREATE TABLE COOKING_TASKS (
    TASK_ID NUMBER(10) PRIMARY KEY,
    ORDER_DETAIL_ID NUMBER(10) NOT NULL,
    STAFF_ID NUMBER(10),
    STATUS VARCHAR2(20) NOT NULL,
    PRIORITY_ORDER NUMBER(5) NOT NULL,
    START_TIME TIMESTAMP,
    END_TIME TIMESTAMP,
    CONSTRAINT FK_TASK_ORDER_DETAIL FOREIGN KEY (ORDER_DETAIL_ID) REFERENCES ORDER_DETAILS (ORDER_DETAIL_ID)
);

CREATE TABLE STORES (
    STORE_ID NUMBER(4) PRIMARY KEY,
    STORE_NAME VARCHAR2(100) NOT NULL,
    PHONE_NUMBER VARCHAR2(20),
    ADDRESS VARCHAR2(255),
    ENABLED NUMBER(1) NOT NULL
);

CREATE TABLE STAFFS (
    STAFF_ID NUMBER(10) PRIMARY KEY,
    STORE_ID NUMBER(10) NOT NULL,
    STAFF_NAME VARCHAR2(100) NOT NULL,
    ROLE VARCHAR2(20) NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    ENABLED NUMBER(1) NOT NULL,
    STAFF_CODE VARCHAR2(20)
);
CREATE UNIQUE INDEX UX_STAFFS_CODE ON STAFFS (UPPER(STAFF_CODE));

CREATE SEQUENCE SEQ_CUSTOMERS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_MENUS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_ORDERS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_ORDER_DETAILS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_COOKING_TASKS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_STAFFS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_STORES START WITH 1 INCREMENT BY 1 NOCACHE;
